export type TranslationsType = typeof translations.en;

/**
 * Narrows an untrusted value -- localStorage, or a languagePreference coming back
 * from the API -- to a Language. The stored preference predates Oromiffa and
 * Tigrigna, and the API column is a plain string, so neither can be trusted to
 * hold one of the four.
 */
export function isLanguage(value: unknown): value is Language {
  return value === "en" || value === "am" || value === "om" || value === "ti";
}

interface LanguageContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: TranslationsType;
}

const LanguageContext = createContext<LanguageContextType>({
  language: "en",
  setLanguage: () => {},
  t: translations.en,
});

const STORAGE_KEY = "yekis-language";

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (isLanguage(saved)) {
        return saved;
      }
      const navLang = navigator.language.toLowerCase();
      if (navLang.startsWith("am")) return "am";
      if (navLang.startsWith("om")) return "om";
      if (navLang.startsWith("ti")) return "ti";
    } catch {
      // Fallback
    }
    return "en";
  });

  const setLanguage = (newLang: Language) => {
    setLanguageState(newLang);
    try {
      localStorage.setItem(STORAGE_KEY, newLang);
      document.documentElement.lang = newLang;
      // Fire analytics event
      events.languageChanged(newLang as any);
    } catch {
      // Ignore
    }
  };

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(
    () => ({
      language,
      setLanguage,
      t: translations[language] || translations.en,
    }),
    [language],
  );

  return React.createElement(LanguageContext.Provider, { value }, children);
}

export function useI18n(): LanguageContextType {
  return useContext(LanguageContext);
}
